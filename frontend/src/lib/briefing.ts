import type { AquacultureResponse, Feature, RiskResponse, ShellfishProps } from "../api/types";

const CLASS_TEXT: Record<string, string> = {
  INSUFFICIENT_DATA: "Insufficient data",
  NO_ELEVATED_SIGNAL: "No elevated signal",
  POTENTIAL_RUNOFF_RISK: "Potential runoff risk",
  ELEVATED_SCREENING_RISK: "Elevated screening risk",
};

/** Build a plain-text (Markdown) environmental briefing from data actually returned by the API. */
export function buildBriefing(area: Feature<ShellfishProps>, aqua: AquacultureResponse, risk: RiskResponse | null): string {
  const p = area.properties;
  const s = p.screening;
  const lines: string[] = [];
  lines.push(`# Environmental screening briefing: ${p.name}`);
  lines.push("");
  lines.push(`Generated by RunoffPulse Ireland on ${new Date().toISOString()}`);
  lines.push("");
  lines.push("> IMPORTANT: This is a software-generated screening summary for situational awareness. It is NOT an official");
  lines.push("> shellfish-harvesting classification, closure, biotoxin result or public-health advisory.");
  lines.push("");
  lines.push("## Area");
  lines.push(`- Designation: ${p.designation} (${p.area_id})`);
  lines.push(`- Parent waterbody: ${p.parent_waterbody_name ?? "unknown"} (${p.parent_waterbody_code})`);
  lines.push(
    `- WFD status of parent waterbody: ${p.parent_waterbody_wfd_status ?? "unknown"} (${p.parent_waterbody_wfd_status_period ?? "n/a"}), official multi-year assessment`,
  );
  lines.push(`- Catchment linkage: ${s?.linkage.basis ?? "n/a"}`);
  lines.push("");
  lines.push("## Screening result");
  if (s) {
    lines.push(`- Classification: ${CLASS_TEXT[s.classification]} (confidence ${s.confidence})`);
    lines.push(`- Score: ${s.score === null ? "not calculated" : s.score.toFixed(2)} (method ${s.engine_version})`);
    lines.push(`- Calculated: ${s.calculated_at}`);
    lines.push("");
    lines.push("### Evidence used");
    (s.evidence.length ? s.evidence : ["None"]).forEach((e) => lines.push(`- ${e}`));
    lines.push("");
    lines.push("### Missing or unusable inputs");
    (s.missing_inputs.length ? s.missing_inputs : ["None"]).forEach((m) => lines.push(`- ${m}`));
    lines.push("");
    lines.push("### Suggested next step");
    lines.push(s.next_step);
  } else {
    lines.push("- No screening result available.");
  }
  lines.push("");
  lines.push("## Nearby EPA monitoring stations (proximity only)");
  if (p.nearby_monitoring_stations.length) {
    p.nearby_monitoring_stations.forEach((st) =>
      lines.push(`- ${st.StationName} (${st.StationID}, ${st.StationType}), ~${st.approx_distance_km} km${st.inside_area ? ", inside area" : ""}`),
    );
  } else lines.push("- None within ~3 km");
  lines.push("");
  lines.push("## Official advisories");
  lines.push(`- Status: ${aqua.official_advisories.status}. ${aqua.official_advisories.message}`);
  aqua.official_advisories.sources.forEach((src) => lines.push(`- ${src.name}: ${src.url}`));
  lines.push("");
  if (risk) {
    lines.push("## Method limitations");
    risk.method.limitations.forEach((l) => lines.push(`- ${l}`));
    lines.push("");
  }
  lines.push("## Data sources");
  lines.push("- EPA Ireland GeoServer (WFD shellfish waters, waterbodies, monitoring stations), CC BY 4.0");
  lines.push("- Met Éireann Cork Airport rainfall, CC BY 4.0");
  lines.push("- OPW waterlevel.ie hydrometric data (provisional)");
  lines.push("- EPA Bathing Water open data, CC BY 4.0");
  return lines.join("\n");
}

export function downloadText(filename: string, text: string): void {
  const blob = new Blob([text], { type: "text/markdown;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}
