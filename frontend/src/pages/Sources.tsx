import { ExternalLink } from "lucide-react";
import { api } from "../api/client";
import type { DataStatus } from "../api/types";
import { useApi } from "../hooks/useApi";
import { Async, Card, DataStatusBadge, PageHeader } from "../components/ui";
import { formatDate, formatDateTime } from "../lib/format";

export default function Sources() {
  const sources = useApi((s) => api.sources(s));
  return (
    <>
      <PageHeader
        title="Data Sources & Provenance"
        subtitle="Every dataset used by RunoffPulse, with publisher, licence, retrieval time and data status. Generated by the reproducible acquisition pipeline (scripts/acquire_all.py)."
      />
      <Async state={sources}>
        {(s) => (
          <div className="space-y-4">
            <Card title="Live feeds">
              <div className="grid grid-cols-1 gap-3 md:grid-cols-2">
                {s.live_feeds.map((f) => (
                  <div key={f.id} className="rounded-lg border border-slate-200 p-3 text-xs">
                    <div className="flex items-center justify-between gap-2">
                      <span className="font-medium text-navy-900">{f.title}</span>
                      <DataStatusBadge status={f.data_status} />
                    </div>
                    <div className="mt-1 text-slate-600">
                      Mode: <strong>{f.mode}</strong> · retrieved {formatDateTime(f.retrieved_at)}
                    </div>
                    {f.error && <div className="mt-1 text-amber-800">{f.error}</div>}
                  </div>
                ))}
              </div>
              <p className="mt-2 text-[11px] text-slate-500">
                Live feeds are polled by the backend and cached; they are periodic snapshots of near-real-time services, not a continuous stream.
                If a feed fails, the last acquired snapshot is used and labelled as such.
              </p>
            </Card>

            <Card title={`Acquired datasets (${s.datasets.length})`} bodyClassName="overflow-x-auto">
              <table className="w-full min-w-[900px] text-left text-xs">
                <thead className="bg-slate-50 text-slate-500">
                  <tr>
                    <th className="px-4 py-2 font-medium">Dataset</th>
                    <th className="px-4 py-2 font-medium">Status</th>
                    <th className="px-4 py-2 font-medium">Publisher · licence</th>
                    <th className="px-4 py-2 text-right font-medium">Records</th>
                    <th className="px-4 py-2 font-medium">Period</th>
                    <th className="px-4 py-2 font-medium">Retrieved</th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-slate-100 align-top">
                  {s.datasets.map((d) => (
                    <tr key={d.id}>
                      <td className="max-w-sm px-4 py-2">
                        <div className="font-medium text-navy-900">{d.title}</div>
                        <div className="mt-0.5 text-slate-500">{d.notes}</div>
                        {d.source_url && (
                          <a href={d.source_url.split(",")[0]} target="_blank" rel="noreferrer" className="mt-0.5 inline-flex items-center gap-1 text-ocean-600 hover:underline">
                            Source <ExternalLink className="h-3 w-3" />
                          </a>
                        )}
                        <div className="text-slate-400">
                          File: {d.file} · CRS: {d.crs}
                        </div>
                      </td>
                      <td className="px-4 py-2">{d.data_status && <DataStatusBadge status={d.data_status} />}</td>
                      <td className="px-4 py-2 text-slate-600">
                        {d.publisher}
                        <div className="text-slate-500">{d.licence}</div>
                      </td>
                      <td className="tabular px-4 py-2 text-right">{d.record_count?.toLocaleString("en-IE") ?? "—"}</td>
                      <td className="tabular whitespace-nowrap px-4 py-2 text-slate-600">
                        {d.period ? `${formatDate(d.period[0])} – ${formatDate(d.period[1])}` : "—"}
                      </td>
                      <td className="tabular whitespace-nowrap px-4 py-2 text-slate-600">{formatDateTime(d.retrieved_at)}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </Card>

            <div className="grid grid-cols-1 gap-4 lg:grid-cols-2">
              <Card title="Derived and community data">
                <ul className="space-y-2 text-xs">
                  {s.derived.map((d) => (
                    <li key={d.id} className="flex items-start justify-between gap-3">
                      <div>
                        <div className="font-medium text-navy-900">{d.title}</div>
                        <div className="text-slate-500">{d.notes}</div>
                      </div>
                      <DataStatusBadge status={d.data_status} />
                    </li>
                  ))}
                </ul>
              </Card>
              <Card title="Not connected (known gaps)">
                <ul className="space-y-2 text-xs">
                  {s.not_connected.map((n) => (
                    <li key={n.title}>
                      <div className="font-medium text-navy-900">{n.title}</div>
                      <div className="text-slate-500">{n.reason}</div>
                    </li>
                  ))}
                </ul>
              </Card>
            </div>

            <Card title="Data status definitions">
              <dl className="grid grid-cols-1 gap-x-4 gap-y-2 text-xs md:grid-cols-[auto_1fr]">
                {(Object.entries(s.data_status_definitions) as [DataStatus, string][]).map(([k, v]) => (
                  <div key={k} className="contents">
                    <dt>
                      <DataStatusBadge status={k} />
                    </dt>
                    <dd className="text-slate-600">{v}</dd>
                  </div>
                ))}
              </dl>
            </Card>
          </div>
        )}
      </Async>
    </>
  );
}
